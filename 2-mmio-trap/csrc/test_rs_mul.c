// Main test function
int main(void)
{
    volatile uint32_t *result_ptr = (volatile uint32_t *)0x10;
    uint32_t passed = 0;
    uint32_t failed = 0;
    
    // Test each vector
    for (uint i = 0; i < NUM_TESTS; i++) {
        uint8_t x = test_vectors[i].x;
        uint8_t y = test_vectors[i].y;
        uint8_t expected = test_vectors[i].expected_z;
        
        uint8_t actual = _rs_mul(x, y);
        
        if (actual == expected) {
            passed++;
        } else {
            failed++;
            // Write failure details to memory for debugging
            // Format: 0xFFXXYYZZ where XX=test_idx, YY=expected, ZZ=actual
            // Start at 0x1C to avoid overwriting completion marker at 0x18
            volatile uint32_t *fail_ptr = (volatile uint32_t *)(0x1C + (failed - 1) * 4);
            *fail_ptr = 0xFF000000 | (i << 16) | (expected << 8) | actual;
        }
    }
    
    // Write summary to 0x10
    // Format: 0xPPPPFFFF where PPPP=passed_count, FFFF=failed_count
    *result_ptr = (passed << 16) | failed;
    
    // Write implementation type to 0x14
    volatile uint32_t *impl_ptr = (volatile uint32_t *)0x14;
    *impl_ptr = QR_OPT;  // 0 for LUT, 1 for iterative
    
    // Success marker at 0x18
    volatile uint32_t *marker_ptr = (volatile uint32_t *)0x18;
    *marker_ptr = 0xDEADBEEF;
    
    return (failed == 0) ? 0 : 1;
}
